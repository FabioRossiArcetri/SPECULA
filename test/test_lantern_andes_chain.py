"""End-to-end check of the dispersed photonic-lantern chain against cbeam.

Needs the exported files and the cbeam ramp used to make them; it is skipped when
they are not in the calibration directory (they are generated by
``tools/pl_export/export_lantern_characterization.py`` and ``export_piston_model.py``,
which need cbeam and PLREC respectively):

    calib/pl_char/pl19_1200_1150_1250_5nm.npz
    calib/pl_rec/pl19_1200_k1282_1150_1250_10nm.npz
    ../cbeam/examples/ifunc/ANDES_400pix_all_modes.fits
    ../PLREC/data/ml/pl19_1200/mw_ramp_41.npz

The ramp is a single DM mode (a petal piston) from -9600 to +9600 nm at the 41
lantern wavelengths, propagated through the full cbeam pipeline: its channel
powers are the reference the sensor must reproduce from the pupil field, and its
piston is the reference the reconstructor and unwrapper must recover.
"""
import os
import unittest
from pathlib import Path

import numpy as np

import specula
specula.init(0)  # Default target device

from specula import cpuArray
from specula.data_objects.electric_field import ElectricField
from specula.data_objects.ifunc import IFunc
from specula.data_objects.lantern_characterization import LanternCharacterization
from specula.data_objects.lantern_cubic_model import LanternCubicModel
from specula.data_objects.simul_params import SimulParams
from specula.processing_objects.dispersed_lantern_sensor import DispersedLanternSensor
from specula.processing_objects.lantern_piston_reconstructor import LanternPistonReconstructor
from specula.processing_objects.spectral_piston_unwrapper import SpectralPistonUnwrapper

from test.specula_testlib import cpu_and_gpu


ROOT = Path(__file__).resolve().parents[1]          # the SPECULA worktree
WORKSPACE = ROOT.parent                              # where cbeam and PLREC live
CHAR = ROOT / 'calib' / 'pl_char' / 'pl19_1200_1150_1250_5nm.npz'
MODEL = ROOT / 'calib' / 'pl_rec' / 'pl19_1200_k1282_1150_1250_10nm.npz'
IFUNC = WORKSPACE / 'cbeam' / 'examples' / 'ifunc' / 'ANDES_400pix_all_modes.fits'
RAMP = WORKSPACE / 'PLREC' / 'data' / 'ml' / 'pl19_1200' / 'mw_ramp_41.npz'

PIXEL_PUPIL = 400          # the grid of the ANDES influence functions
PIXEL_PITCH = 0.0975       # [m] the ELT pupil sampling of the ANDES simulations

HAVE_DATA = all(p.exists() for p in (CHAR, MODEL, IFUNC, RAMP))


class _Data:
    '''Loaded once per device: the exported files, the cbeam ramp and the pupil'''
    _cache = {}

    @classmethod
    def get(cls, target_device_idx=None):
        key = target_device_idx
        if key not in cls._cache:
            cls._cache[key] = dict(
                char=LanternCharacterization.restore(str(CHAR), target_device_idx=target_device_idx),
                model=LanternCubicModel.restore(str(MODEL), target_device_idx=target_device_idx),
                ifunc=IFunc.restore(str(IFUNC), target_device_idx=target_device_idx),
                ramp=np.load(RAMP, allow_pickle=False))
        return cls._cache[key]


def make_ef(xp, coeff, target_device_idx=None):
    '''Pupil field of a DM configuration: the ANDES influence functions in nm'''
    d = _Data.get(target_device_idx)
    ifunc = d['ifunc']
    ef = ElectricField(PIXEL_PUPIL, PIXEL_PUPIL, PIXEL_PITCH,
                       target_device_idx=target_device_idx)
    coeff = np.asarray(coeff, float).ravel()
    n_modes = len(coeff)
    opd = coeff @ np.asarray(cpuArray(ifunc.influence_function), float)[:n_modes]
    mask = np.asarray(cpuArray(ifunc.mask_inf_func)) > 0
    ef.A[:] = xp.asarray(mask, dtype=ef.dtype)
    phase = np.zeros((PIXEL_PUPIL, PIXEL_PUPIL), dtype=np.float64)
    phase[mask] = opd
    ef.phaseInNm[:] = xp.asarray(phase, dtype=ef.dtype)
    ef.generation_time = 1
    return ef


def simul_params():
    return SimulParams(pixel_pupil=PIXEL_PUPIL, pixel_pitch=PIXEL_PITCH,
                       root_dir='.', total_time=0.1, time_step=0.001)


def run(obj, inputs, t=1):
    for name, value in inputs.items():
        obj.inputs[name].set(value)
    obj.setup()
    obj.check_ready(t)
    obj.trigger()
    obj.post_trigger()


@unittest.skipUnless(HAVE_DATA, 'the exported PL files and the cbeam ramp are not available')
class TestPLAndesChain(unittest.TestCase):

    @cpu_and_gpu
    def test_sensor_reproduces_the_cbeam_channel_powers(self, target_device_idx, xp):
        d = _Data.get(target_device_idx)
        char, ramp = d['char'], d['ramp']
        sensor = DispersedLanternSensor(simul_params(), char, pad_factor=4,
                                   target_device_idx=target_device_idx)
        ramp_wl = np.asarray(ramp['wavelengths'], float)
        coeff = np.asarray(ramp['coeff_matrix'], float)          # (n_steps, 1)
        power = np.asarray(ramp['power_spectra'], float)         # (n_wl, n_steps, n_ports)
        char_wl = cpuArray(char.wavelengths_nm)

        # a few ramp steps, symmetrically in the piston range
        steps = [0, len(coeff) // 4, len(coeff) // 2, 3 * len(coeff) // 4, len(coeff) - 1]
        worst = 0.0
        for step in steps:
            run(sensor, {'in_ef': make_ef(xp, coeff[step], target_device_idx)})
            signals = cpuArray(sensor.outputs['out_signals'].value)      # (n_wl_char, n_ports)
            for i, wl in enumerate(char_wl):
                j = int(np.argmin(np.abs(ramp_wl - wl)))
                self.assertLess(abs(ramp_wl[j] - wl), 0.5)
                ref = power[j, step, :]
                scale = max(ref.max(), 1e-12)
                worst = max(worst, float(np.max(np.abs(signals[i] - ref))) / scale)
        print(f'\n  sensor vs cbeam channel powers: max relative difference {worst:.2e}')
        self.assertLess(worst, 5e-2)

    @cpu_and_gpu
    def test_full_chain_recovers_the_ramp_piston(self, target_device_idx, xp):
        d = _Data.get(target_device_idx)
        char, model, ramp = d['char'], d['model'], d['ramp']
        sensor = DispersedLanternSensor(simul_params(), char, pad_factor=4,
                                   target_device_idx=target_device_idx)
        rec = LanternPistonReconstructor(model, target_device_idx=target_device_idx)
        unwrap = SpectralPistonUnwrapper(model, target_device_idx=target_device_idx)

        coeff = np.asarray(ramp['coeff_matrix'], float)
        # within the capture range of the model, and away from the range edges
        span = min(model.span_nm, 2000.0)
        steps = [i for i, c in enumerate(coeff[:, 0]) if abs(c) <= 0.9 * span]
        self.assertGreater(len(steps), 5)
        worst = 0.0
        for step in steps[::max(1, len(steps) // 12)]:
            run(sensor, {'in_ef': make_ef(xp, coeff[step], target_device_idx)})
            signals = sensor.outputs['out_signals']
            run(rec, {'in_signals': signals})
            run(unwrap, {'in_pistons_wrapped': rec.outputs['out_pistons_wrapped'],
                         'in_confidence': rec.outputs['out_confidence']})
            pistons = cpuArray(unwrap.outputs['out_pistons'].value)
            truth = coeff[step, 0]
            worst = max(worst, abs(float(pistons[0]) - truth))
            self.assertGreater(float(cpuArray(unwrap.outputs['out_agreement'].value)[0]), 0.5)
        print(f'\n  full chain on the ramp: max piston error {worst:.1f} nm')
        self.assertLess(worst, 100.0)


if __name__ == '__main__':
    unittest.main()
